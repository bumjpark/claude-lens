def format_interactions(interactions, previous=None) -> str:
    lines = []
    # 청크 경계 때문에 직전 상호작용이 안 보이면 "해봐"류의 짧은 확인 응답이 맥락 없다고
    # 오판되는 문제가 있어서, 청크 첫 항목 앞에 직전 상호작용을 참고용으로 붙여준다
    # (채점 대상은 아니고 맥락 파악용).
    if previous is not None:
        lines.append(
            "### 직전 상호작용 (참고용 — 채점 대상 아님, 바로 다음 상호작용의 맥락 파악용)\n"
            f"프롬프트: {previous.prompt_text}\n"
            f"응답: {previous.response_text[:500]}"
        )
    for i, log in enumerate(interactions):
        flags = []
        if log.is_retry:
            flags.append("재요청")
        if log.is_code_request:
            flags.append("코드요청")
        if log.is_error_request:
            flags.append("오류해결")
        if log.is_review_request:
            flags.append("리뷰요청")
        if log.is_design_request:
            flags.append("설계질문")
        flag_str = f" [{', '.join(flags)}]" if flags else ""
        lines.append(
            f"### 상호작용 {i + 1} (id={log.id}){flag_str}\n"
            f"프롬프트: {log.prompt_text}\n"
            f"응답: {log.response_text[:500]}"
        )
    return "\n\n".join(lines)


